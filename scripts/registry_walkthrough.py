"""Runs the Registry Intelligence workflow end to end against a throw-away database; writes a Markdown transcript.

Usage (repo root, backend venv active):
    python scripts/registry_walkthrough.py [--output README.md]

The real FastAPI app runs in-process with token authentication enabled (synthetic tokens are generated for this
run and never written anywhere), so every response shown is genuine output of this code base. All records are
fictional.
"""

from __future__ import annotations

import argparse
import json
import secrets
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from alembic import command  # noqa: E402
from fastapi.testclient import TestClient  # noqa: E402

from app.core.config import Settings  # noqa: E402
from app.db.migrations_check import alembic_config  # noqa: E402
from app.db.session import create_db_engine  # noqa: E402
from app.main import create_app  # noqa: E402
from app.models import SupplyRelationship  # noqa: E402
from app.models.enums import Provenance, RelationshipType  # noqa: E402
from sqlalchemy.orm import Session  # noqa: E402

R = "/api/v1/registry"
OUT: list[str] = []


def say(text: str = "") -> None:
    OUT.append(text)


def show(title: str, payload: object, keys: tuple[str, ...] | None = None) -> None:
    if keys and isinstance(payload, dict):
        payload = {k: payload[k] for k in keys if k in payload}
    say(f"**{title}**")
    say("```json")
    say(json.dumps(payload, indent=2, default=str)[:1800])
    say("```")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default=str(ROOT / "docs" / "registry" / "WALKTHROUGH.md"))
    args = ap.parse_args()
    tokens = {role: secrets.token_urlsafe(24) for role in ("viewer", "editor", "reviewer", "admin")}
    table = ",".join(f"{t}:{role}-demo:{role}" for role, t in tokens.items())
    H = {role: {"Authorization": f"Bearer {t}"} for role, t in tokens.items()}

    with tempfile.TemporaryDirectory() as tmp:
        url = f"sqlite:///{Path(tmp, 'walk.db').as_posix()}"
        command.upgrade(alembic_config(url), "head")
        settings = Settings(_env_file=None, environment="test", database_url=url, data_dir=Path(tmp), api_tokens=table)
        engine = create_db_engine(url)
        with TestClient(create_app(settings, engine)) as c:
            say("# Registry Intelligence walkthrough (executed)")
            say()
            say(
                "Generated by `python scripts/registry_walkthrough.py` against a throw-away SQLite database with token "
                "authentication enabled. All names are fictional. Tokens are random per run and not shown."
            )
            say()

            say("## 1. Identity and roles")
            show("GET /registry/me as reviewer", c.get(f"{R}/me", headers=H["reviewer"]).json())
            r = c.post(
                f"{R}/suppliers", json={"name": "x", "country_or_region": "DE", "category": "c"}, headers=H["viewer"]
            )
            show("A viewer trying to create a record is refused (and the refusal is audited)", r.json())

            say("## 2. Create canonical records (editor)")
            mk = lambda **f: c.post(
                f"{R}/suppliers",
                json={"country_or_region": "Germany", "category": "Electronics"} | f,
                headers=H["editor"],
            ).json()  # noqa: E731
            a = mk(name="Acme Components GmbH", address="1 Main Street")
            b = mk(name="ACME Components G.m.b.H.")
            d = mk(name="Birch Furniture", country_or_region="Sweden", category="Furniture")
            show(
                "Created record (note stable code, version and provenance)",
                a,
                ("type", "id", "code", "version", "lifecycle", "normalized"),
            )
            c.post(
                f"{R}/suppliers/{b['id']}/aliases",
                json={"alias": "Acme Old", "kind": "FORMER_NAME"},
                headers=H["editor"],
            )
            fac = c.post(
                f"{R}/facilities",
                json={"name": "Dock One", "facility_type": "WAREHOUSE", "country_or_region": "Germany"},
                headers=H["editor"],
            ).json()
            with Session(engine) as s, s.begin():
                s.add(
                    SupplyRelationship(
                        relationship_code="WALK-REL-1",
                        relationship_type=RelationshipType.SUPPLIES,
                        supplier_id=b["id"],
                        target_facility_id=fac["id"],
                        provenance=Provenance.USER_PROVIDED,
                    )
                )

            say("## 3. Search: exact versus approximate, with reasons")
            show(
                "GET /registry/search?q=Acme+Old (an alias)",
                [
                    {k: i[k] for k in ("name", "exact", "match_reasons")}
                    for i in c.get(f"{R}/search", params={"q": "Acme Old"}, headers=H["viewer"]).json()["items"]
                ],
            )
            show(
                "GET /registry/search?q=Acmee Compnents (typos, approximate only)",
                [
                    {k: i[k] for k in ("name", "exact", "approximate", "match_reasons")}
                    for i in c.get(f"{R}/search", params={"q": "Acmee Compnents"}, headers=H["viewer"]).json()["items"]
                ],
            )

            say("## 4. Duplicate detection (reviewer): bounded, deterministic, versioned")
            run = c.post(f"{R}/candidates/generate", json={"entity_type": "SUPPLIER"}, headers=H["reviewer"]).json()
            show(
                "Matching run",
                run,
                (
                    "run_uid",
                    "config_version",
                    "entities_considered",
                    "blocks",
                    "pairs_compared",
                    "candidates_found",
                    "status",
                ),
            )
            cand = c.get(f"{R}/candidates", headers=H["viewer"]).json()["items"][0]
            show(
                "Candidate evidence (a similarity score, not a probability)",
                cand,
                ("id", "score", "tier", "hard_conflict", "status"),
            )
            show("Signals", cand["evidence"]["signals"])
            r = c.post(
                f"{R}/candidates/{cand['id']}/decision",
                json={"decision": "CONFIRMED_DUPLICATE", "reason": "same registered address"},
                headers=H["editor"],
            )
            show("An editor cannot decide (needs reviewer)", r.json())
            d1 = c.post(
                f"{R}/candidates/{cand['id']}/decision",
                json={"decision": "CONFIRMED_DUPLICATE", "reason": "same registered address"},
                headers=H["reviewer"],
            ).json()
            show("Reviewer confirms", d1, ("id", "status"))

            say("## 5. Merge preview, then execution (admin)")
            body = {
                "entity_type": "SUPPLIER",
                "survivor_id": a["id"],
                "merged_id": b["id"],
                "survivor_version": a["version"],
                "merged_version": b["version"],
                "candidate_id": cand["id"],
                "reason": "confirmed same legal entity",
            }
            pv = c.post(f"{R}/merges/preview", json=body, headers=H["reviewer"]).json()
            show(
                "Preview before any decision: name conflict blocks execution",
                {
                    "can_execute": pv["can_execute"],
                    "blockers": pv["blockers"],
                    "relationship_impact": pv["relationship_impact"],
                },
            )
            body["field_decisions"] = {"name": {"choice": "KEEP_SURVIVOR"}}
            pv = c.post(f"{R}/merges/preview", json=body, headers=H["reviewer"]).json()
            show("Preview with the decision", {"can_execute": pv["can_execute"], "blockers": pv["blockers"]})
            r = c.post(f"{R}/merges", json=body, headers=H["reviewer"])
            show("A reviewer cannot execute (needs admin)", r.json())
            m = c.post(f"{R}/merges", json=body, headers=H["admin"]).json()
            show(
                "Merge executed",
                m,
                ("id", "status", "actor", "survivor_version_before", "survivor_version_after", "reassigned_count"),
            )
            show(
                "Merged record is a tombstone, not deleted",
                c.get(f"{R}/suppliers/{b['id']}", headers=H["viewer"]).json(),
                ("id", "lifecycle", "identity"),
            )
            show(
                "Old alias now resolves to the canonical record",
                [
                    {k: i[k] for k in ("id", "name", "match_reasons")}
                    for i in c.get(f"{R}/search", params={"q": "Acme Old"}, headers=H["viewer"]).json()["items"]
                ],
            )
            surv = c.get(f"{R}/suppliers/{a['id']}", headers=H["viewer"]).json()
            show("The relationship moved to the survivor", surv["relationships"])

            say("## 6. Compensation")
            comp = c.post(
                f"{R}/merges/{m['id']}/compensate", json={"reason": "demonstration of undo"}, headers=H["admin"]
            ).json()
            show("Compensated (allowed because nothing changed since)", comp, ("id", "status", "compensated_by"))
            show(
                "Merged record is active again",
                c.get(f"{R}/suppliers/{b['id']}", headers=H["viewer"]).json(),
                ("id", "lifecycle", "version"),
            )

            say("## 7. Quality")
            q = c.post(f"{R}/quality/run", json={}, headers=H["editor"]).json()
            show("Quality run", q, ("config_version", "entities_assessed", "average_overall", "dimension_averages"))
            show(
                "Issues (actionable)",
                c.get(f"{R}/quality/issues", params={"limit": 3}, headers=H["viewer"]).json()["items"],
            )

            say("## 8. Audit")
            ver = c.get(f"{R}/audit/verify", headers=H["admin"]).json()
            show("Hash-chain verification", ver)
            ev = c.get(f"{R}/audit", params={"limit": 6}, headers=H["reviewer"]).json()["items"]
            show(
                "Latest audit events",
                [
                    {k: e[k] for k in ("action", "actor", "actor_role", "outcome", "target_type", "target_id")}
                    for e in ev
                ],
            )
            assert d["id"]
        engine.dispose()

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(OUT) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
